import assert from "node:assert/strict";
import "../experience-math.js";
const M = globalThis.PulseMath;
const rows = Array.from({ length:100 }, (_, i) => ({ date: new Date(Date.UTC(2026,0,1+i)).toISOString().slice(0,10), close:100+i }));
assert.equal(M.sma(rows,20).at(-1),189.5);
assert.equal(M.sma(rows,60).at(-1),169.5);
assert.equal(M.trend(rows).tone,'positive');
assert.equal(M.trend(rows,false).ready,false);
assert.equal(M.trend(rows.slice(0,59)).ready,false);
const gap = rows.filter((_,i) => i!==80);
assert.equal(M.trend(gap).ready,false);
assert.equal(M.realizedVol(gap,30),null);
assert.equal(M.realizedVol(rows,91),null);
assert.ok(M.realizedVol(rows,30)>0);
const flat = rows.map(r => ({...r,close:100}));
assert.equal(M.realizedVol(flat,30),0);
const walls = M.walls([{strike:90,callOi:9,putOi:2,callGex:100},{strike:110,callOi:99,putOi:1,callGex:0},{strike:70,callOi:0,putOi:100},{strike:120,callOi:99,putOi:null}]);
assert.equal(walls.call.strike,110);
assert.equal(walls.put.strike,70);
assert.equal(M.walls([]).call,null);
assert.equal(M.range(100,20,365.25).move,20);
assert.equal(M.realizedVol(rows,NaN),null);
assert.equal(M.range(100,null,30),null);
assert.equal(M.fresh('bad'),false);
assert.equal(M.fresh('2026-01-01T00:00:00Z',Date.parse('2026-01-01T07:00:00Z')),false);
assert.equal(M.fresh('2026-01-01T00:00:00Z',Date.parse('2026-01-01T02:00:00Z')),true);
console.log('Experience tests passed: MA, gaps, freshness, independent OI walls and volatility.');
